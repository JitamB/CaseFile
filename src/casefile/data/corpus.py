"""The text layer — §24's honesty controls.

`scm.py` decides what happened and `generator.py` decides what each department
wrote down. This file decides **what the words were**, which is the half the
retrieval and extraction stages actually read.

Four controls, from §24, and each one is a rule this module obeys rather than a
claim it makes:

1. **Generate once, freeze, commit.** No live generation at demo time, so the
   model writing tickets is never the model reading them in the same run.
2. **~85% irrelevant traffic** — password resets, billing queries, feature
   requests. *Finding a needle in a stack of needles proves nothing.*
3. **Deliberately misleading documents** — a ticket that mentions the integration
   and concludes it was fine; a CRM note blaming pricing with no evidence;
   genuinely ambiguous notes.
4. **The noise is templates; the signal is authored.** The irrelevant traffic is
   template-generated from a vocabulary sampled per §21 Layer 1 — tens of
   thousands of documents that need no model. Only the few dozen that carry
   signal or misdirection are written by hand, under `data/corpus/authored/`.

**What is committed, and the one place this departs from §41.2.** §41.2 lists
`data/corpus/` as committed. The authored documents are — they are a few
kilobytes and they are the part a reviewer has to be able to read in a diff. The
~46k template documents are **regenerated byte-identically from the seed** by
`make data` instead of being carried in git, because 30-odd MB of generated prose
is exactly the dead weight §41.2's own ignore list objects to. §24's requirement
is that nothing is generated *by a model* at demo time, and templates are not a
model.
"""

from __future__ import annotations

import random
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

import yaml

AUTHORED_DIR = Path(__file__).resolve().parents[3] / "data" / "corpus" / "authored"

#: §24's ~85%. Categories a support desk fills its day with and no investigation
#: has ever turned on. The weights are what make the claim measurable.
NOISE_CATEGORIES: tuple[str, ...] = ("how_to", "billing_query", "access")
SIGNAL_CATEGORIES: tuple[str, ...] = ("integration", "performance")
CATEGORY_WEIGHTS = {
    "how_to": 0.31,
    "billing_query": 0.29,
    "access": 0.25,
    "integration": 0.09,
    "performance": 0.06,
}


class CorpusError(ValueError):
    """An authored document that does not attach to anything in the corpus."""


@dataclass(frozen=True)
class Authored:
    """One hand-written document. `front` is its YAML header verbatim."""

    doc_id: str
    table: str
    role: str
    front: dict[str, object]
    body: str

    @property
    def account(self) -> str | None:
        value = self.front.get("account")
        return str(value) if value else None

    @property
    def date(self) -> str:
        return str(self.front["date"])

    def get(self, key: str, default: str = "") -> str:
        value = self.front.get(key)
        return default if value is None else str(value)


def load_authored(directory: Path | str = AUTHORED_DIR) -> list[Authored]:
    """Every committed document, in filename order so the corpus is stable."""
    documents: list[Authored] = []
    for path in sorted(Path(directory).glob("*.md")):
        front, body = _split_front_matter(path)
        for required in ("doc_id", "table", "date", "role"):
            if required not in front:
                raise CorpusError(f"{path.name} has no {required!r} in its front matter")
        documents.append(
            Authored(
                doc_id=str(front["doc_id"]),
                table=str(front["table"]),
                role=str(front["role"]),
                front=front,
                body=body,
            )
        )

    seen = [d.doc_id for d in documents]
    if len(set(seen)) != len(seen):
        raise CorpusError(f"duplicate doc_id among authored documents: {sorted(seen)}")
    return documents


def _split_front_matter(path: Path) -> tuple[dict[str, object], str]:
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        raise CorpusError(f"{path.name} does not open with a YAML front-matter fence")
    _, header, body = text.split("---\n", 2)
    front = yaml.safe_load(header)
    if not isinstance(front, dict):
        raise CorpusError(f"{path.name} has a front matter that is not a mapping")
    return front, " ".join(body.split())


