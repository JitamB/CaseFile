def category(rng: random.Random) -> str:
    """A ticket category, weighted so §24's 85% noise floor is a measurement."""
    keys = list(CATEGORY_WEIGHTS)
    return rng.choices(keys, [CATEGORY_WEIGHTS[k] for k in keys])[0]


def subject(rng: random.Random, kind: str) -> str:
    return rng.choice(_SUBJECTS[kind])


def ticket_body(rng: random.Random, kind: str, account_name: str) -> str:
    return (
        f"{rng.choice(_OPENERS)} {rng.choice(_BODIES[kind])}. "
        f"Account is {account_name}. {rng.choice(_CLOSERS)}"
    )


def ticket_message(rng: random.Random) -> str:
    return rng.choice(_MESSAGE_TEMPLATES)


def note_body(rng: random.Random) -> str:
    return rng.choice(_NOTE_TEMPLATES).format(topic=rng.choice(_NOTE_TOPICS))


def news(rng: random.Random) -> tuple[str, str, str]:
    """A source, a headline and a body for one ordinary industry item."""
    return (
        rng.choice(_NEWS_SOURCES),
        rng.choice(_NEWS_HEADLINES),
        rng.choice(_NEWS_BODIES),
    )


# ── Measuring the noise floor ────────────────────────────────────────────────


def is_noise(topic: str, authored_role: str | None = None) -> bool:
    """Whether a document is part of §24's irrelevant traffic.

    A document counts as *not* noise if it is one of the authored ones — signal,
    misdirection and the deliberately ambiguous alike, because all three are
    things an investigator would want to read — or if its topic maps to a driver
    the registry can test.
    """
    if authored_role is not None:
        return authored_role == "noise"
    return topic in NOISE_CATEGORIES


def noise_share(topics: Sequence[tuple[str, str | None]]) -> float:
    """The share of `(topic, authored_role)` pairs that are irrelevant traffic."""
    if not topics:
        return 0.0
    return sum(1 for topic, role in topics if is_noise(topic, role)) / len(topics)


def main() -> None:
    """`make corpus` — validate the authored documents and report the floor.

    §41.3 describes this target as needing an API key. It does not: §24's fourth
    control is that *"the noise is templates; the signal is authored"*, so the
    only model in the corpus is the one that wrote the two dozen files under
    `data/corpus/authored/` by hand, once, into git. Regenerating needs the seed
    and nothing else, which is also why CI can do it.
    """
    from collections import Counter

    documents = load_authored()
    roles = Counter(d.role for d in documents)
    tables = Counter(d.table for d in documents)

    print(f"{len(documents)} authored documents under {AUTHORED_DIR.name}/")
    for role, count in sorted(roles.items()):
        print(f"  {role:14} {count}")
    for table, count in sorted(tables.items()):
        print(f"  {table:24} {count}")
    print()
    print("template category weights (§24's ~85% noise floor):")
    noise = sum(CATEGORY_WEIGHTS[k] for k in NOISE_CATEGORIES)
    for name, weight in sorted(CATEGORY_WEIGHTS.items(), key=lambda kv: -kv[1]):
        marker = "noise " if name in NOISE_CATEGORIES else "signal"
        print(f"  {marker} {name:14} {weight:.0%}")
    print(f"  -> {noise:.0%} irrelevant traffic by construction")


if __name__ == "__main__":
    main()
